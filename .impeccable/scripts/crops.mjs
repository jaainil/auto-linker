import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
const ctx = await browser.newContext({ viewport: { width: 390, height: 900 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
await page.goto('http://localhost:4322/', { waitUntil: 'networkidle' });
await page.evaluate(() => { document.querySelectorAll('.reveal').forEach(e => e.classList.add('is-in')); document.querySelector('.nav')?.remove(); });
await page.waitForTimeout(500);
await page.locator('.demo__toolbar').screenshot({ path: '.impeccable/review/crop-toolbar.png' });
await page.locator('.hero__status').screenshot({ path: '.impeccable/review/crop-status.png' });
await page.setViewportSize({ width: 1440, height: 1000 });
await page.waitForTimeout(300);
await page.locator('#api .code-card').first().screenshot({ path: '.impeccable/review/crop-code.png' });
await page.locator('.dod').screenshot({ path: '.impeccable/review/crop-dod.png' });
await browser.close();
