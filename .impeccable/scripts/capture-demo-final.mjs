import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const page = await ctx.newPage();
await page.goto('http://localhost:4321/', { waitUntil: 'networkidle' });
await page.locator('#demo').scrollIntoViewIfNeeded();
await page.waitForTimeout(300);
await page.locator('.demo').screenshot({ path: '.impeccable/review/demo-before.png' });
await page.click('[data-run]');
await page.waitForTimeout(1200);
await page.locator('.demo').screenshot({ path: '.impeccable/review/demo-run.png' });
await page.click('[data-view="html"]');
await page.waitForTimeout(300);
await page.locator('.demo').screenshot({ path: '.impeccable/review/demo-html.png' });
await page.click('[data-recover]');
await page.waitForTimeout(500);
await page.locator('.demo').screenshot({ path: '.impeccable/review/demo-recovered.png' });
await ctx.close();

const mctx = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
const m = await mctx.newPage();
await m.goto('http://localhost:4321/', { waitUntil: 'networkidle' });
await m.locator('#demo').scrollIntoViewIfNeeded();
await m.click('[data-run]');
await m.waitForTimeout(1200);
await m.locator('.demo').screenshot({ path: '.impeccable/review/demo-run-mobile.png' });
await mctx.close();
await browser.close();
console.log('done');
